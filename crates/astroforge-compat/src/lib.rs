//! AstroForge 对照测试核心。
//!
//! 分级对照（参见架构设计）：
//!
//! | 级别 | 对照目标                                       |
//! | ---- | ---------------------------------------------- |
//! | 1    | 文件结构（产物目录树等价）                      |
//! | 2    | `manifest.json`（去时间戳、去 hash 后字段等价） |
//! | 3    | 资源图（路径、digest）                          |
//! | 4    | JS AST（规范化后的等价性判定）                  |
//! | 5    | 运行时调用序列（`__ce__` / `__cc__` 调用图）    |
//! | 6    | 模拟器 / 真机冒烟测试                           |
//!
//! 本 crate 实现 1–5 级；级别 6 由 `astroforge-device` 配合外部夹具承担。
//!
//! 当前已落地：
//! - [`ir_diff`]：通用 JSON 文档 diff，是 2 / 4 / 5 级的共享底层。

